// ScanStaleFeeds is the worker sweep that turns a feed that has not been
// successfully polled inside its staleness window into a visible exception.
func (s *CalendarService) ScanStaleFeeds(ctx context.Context, now time.Time) (*ScanStaleResult, error) {
	feeds, err := s.store.ListActiveFeeds(ctx)
	if err != nil {
		return nil, err
	}

	result := &ScanStaleResult{}
	for _, feed := range feeds {
		h := feedHealth(feed, now)
		if !h.Stale {
			continue
		}
		exc := &CalendarException{
			TenantID:   feed.TenantID,
			PropertyID: feed.PropertyID,
			FeedID:     feed.ID,
			Kind:       ExceptionKindStaleFeed,
			Severity:   ExceptionSeverityWarning,
			Status:     ExceptionStatusOpen,
			Message:    "calendar feed has not been successfully polled inside its staleness window",
			DedupeKey:  "feed:" + feed.ID,
			CreatedAt:  now,
		}
		created, err := s.store.InsertException(ctx, s.pool, exc)
		if err != nil {
			return nil, err
		}
		if created {
			result.StaleFeeds++
		}
	}
	return result, nil
}

type ScanStaleResult struct {
	StaleFeeds int `json:"stale_feeds"`
}

func (s *CalendarService) recordFeedFailure(ctx context.Context, feed *CalendarFeed, message string, at time.Time) error {
	return database.WithTx(ctx, s.pool, func(ctx context.Context, tx pgx.Tx) error {
		result := &IngestResult{FeedID: feed.ID}
		return s.recordFeedFailureTx(ctx, tx, feed, message, at, result)
	})
}

func (s *CalendarService) recordFeedFailureTx(ctx context.Context, tx pgx.Tx, feed *CalendarFeed, message string, at time.Time, result *IngestResult) error {
	if err := s.store.RecordPollFailure(ctx, tx, feed.ID, feed.TenantID, message, at); err != nil {
		return err
	}
	exc := &CalendarException{
		TenantID:   feed.TenantID,
		PropertyID: feed.PropertyID,
		FeedID:     feed.ID,
		Kind:       ExceptionKindFeedFailure,
		Severity:   ExceptionSeverityCritical,
		Status:     ExceptionStatusOpen,
		Message:    "calendar feed poll failed: " + message,
		DedupeKey:  "feed:" + feed.ID,
		CreatedAt:  at,
	}
	created, err := s.store.InsertException(ctx, tx, exc)
	if err != nil {
		return err
	}
	if created {
		result.ExceptionsCreated++
	}
	return nil
}

func newFeed(params FeedParams) (*CalendarFeed, error) {
	if params.TenantID == "" || params.PropertyID == "" {
		return nil, fmt.Errorf("%w: tenant_id and property_id are required", ErrInvalidFeed)
	}
	if strings.TrimSpace(params.Source) == "" {
		return nil, fmt.Errorf("%w: source is required", ErrInvalidFeed)
	}
	if strings.TrimSpace(params.URL) == "" {
		return nil, fmt.Errorf("%w: url is required", ErrInvalidFeed)
	}
	if params.PropertyTimezone != "" {
		if _, err := time.LoadLocation(params.PropertyTimezone); err != nil {
			return nil, fmt.Errorf("%w: unknown property timezone %q", ErrInvalidFeed, params.PropertyTimezone)
		}
	}
	status := params.Status
	if status == "" {
		status = FeedStatusActive
	}
	if !validFeedStatus(status) {
		return nil, fmt.Errorf("%w: invalid status %q", ErrInvalidFeed, status)
	}

	staleAfter := params.StaleAfterMinutes
	if staleAfter <= 0 {
		staleAfter = DefaultStaleAfterMinutes
	}
	turnaround := params.MinimumTurnaroundMinutes
	if turnaround <= 0 {
		turnaround = DefaultMinimumTurnaroundMinutes
	}
	timezone := params.PropertyTimezone
	if timezone == "" {
		timezone = "Asia/Kolkata"
	}

	return &CalendarFeed{
		TenantID:                 params.TenantID,
		PropertyID:               params.PropertyID,
		Source:                   params.Source,
		URL:                      params.URL,
		Status:                   status,
		PropertyTimezone:         timezone,
		StaleAfterMinutes:        staleAfter,
		MinimumTurnaroundMinutes: turnaround,
		Version:                  1,
	}, nil
}

func validFeedStatus(status string) bool {
	switch status {
	case FeedStatusActive, FeedStatusPaused, FeedStatusDisabled:
		return true
	default:
		return false
	}
}

func hasRole(roles []string, targets ...string) bool {
	for _, r := range roles {
		for _, t := range targets {
			if r == t {
				return true
			}
		}
	}
	return false
}

func (s *CalendarService) authorizeProperty(ctx context.Context, tenantID, propertyID string) error {
	if s.authorizer == nil {
		return nil
	}
	return s.authorizer.RequireResourceAccess(ctx, tenantID, "property", propertyID)
}
