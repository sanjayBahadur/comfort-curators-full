// ResourceAuthorizer is implemented by the tenancy service. When present it
// enforces tenant and property scope before any resource is touched.
type ResourceAuthorizer interface {
	RequireResourceAccess(ctx context.Context, resourceTenantID, resourceType, resourceID string) error
}

// CalendarService implements read-only iCalendar feed ingestion and the
// reservation workflow built on top of it. External calendar events can only
// enter or change through feed polling; there is no application path that
// edits or deletes an external event directly, and feed configuration rejects
// the Jarvis role. Normalized reservations are the operational source of
// truth, conflicts are resolved by humans with an immutable audit trail, and
// turnover and inspection proposals are generated by a deterministic rule
// that never runs against a stale feed.
type CalendarService struct {
	pool       *pgxpool.Pool
	store      *CalendarStore
	client     *http.Client
	authorizer ResourceAuthorizer
	auditStore *audit.AuditStore
}

func NewCalendarService(pool *pgxpool.Pool) *CalendarService {
	return &CalendarService{
		pool:       pool,
		store:      NewCalendarStore(pool),
		client:     &http.Client{Timeout: DefaultFeedPollTimeout},
		auditStore: audit.NewAuditStore(pool),
	}
}

func (s *CalendarService) WithAuthorizer(a ResourceAuthorizer) *CalendarService {
	s.authorizer = a
	return s
}

// WithAudit replaces the audit store used for conflict-resolution evidence.
func (s *CalendarService) WithAudit(a *audit.AuditStore) *CalendarService {
	s.auditStore = a
	return s
}

// ---- feed configuration (mutations are forbidden to the Jarvis) ----

func (s *CalendarService) CreateFeed(ctx context.Context, params FeedParams, roles []string) (*CalendarFeed, error) {
	if hasRole(roles, RoleJarvis, RoleSuperhost) {
		return nil, ErrSuperhostCannotMutate
	}
	if err := s.authorizeProperty(ctx, params.TenantID, params.PropertyID); err != nil {
		return nil, err
	}

	feed, err := newFeed(params)
	if err != nil {
		return nil, err
	}
	if err := s.store.InsertFeed(ctx, feed); err != nil {
		return nil, err
	}
	return feed, nil
}

func (s *CalendarService) SetFeedStatus(ctx context.Context, tenantID, feedID, status string, roles []string) (*CalendarFeed, error) {
	if hasRole(roles, RoleJarvis, RoleSuperhost) {
		return nil, ErrSuperhostCannotMutate
	}
	feed, err := s.store.GetFeed(ctx, tenantID, feedID)
	if err != nil {
		return nil, err
	}
	if err := s.authorizeProperty(ctx, tenantID, feed.PropertyID); err != nil {
		return nil, err
	}
	if !validFeedStatus(status) {
		return nil, fmt.Errorf("%w: invalid status %q", ErrInvalidFeed, status)
	}
	return s.store.SetFeedStatus(ctx, tenantID, feedID, status, time.Now().UTC())
}

